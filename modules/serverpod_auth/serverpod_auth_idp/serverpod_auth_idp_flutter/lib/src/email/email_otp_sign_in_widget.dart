import 'package:flutter/material.dart';
import 'package:serverpod_auth_core_flutter/serverpod_auth_core_flutter.dart';

import '../common/widgets/password_requirements/requirements.dart';
import 'email_otp_auth_controller.dart';
import 'email_otp_flow_view.dart';
import 'forms/verification.dart';

/// A widget that provides passwordless email authentication, where users sign
/// in or sign up with a one-time password (OTP) sent to their email.
///
/// Users enter their email to receive a code. Verifying it signs in existing
/// accounts, while emails without an account continue to a screen to accept
/// the terms and create one. To let users also sign in with their password,
/// and reset it, from the start screen, set [allowPasswordSignIn] to `true`.
///
/// The server must be configured to send the codes, see
/// `EmailIdpConfig.sendOtpLoginVerificationCode`. For the password based flow
/// with separate sign-in and sign-up screens, use `EmailSignInWidget`.
///
/// The widget can manage its own authentication state, or you can provide an
/// external [controller] for advanced use cases like sharing state across
/// multiple widgets or integrating with state management solutions.
///
/// When [controller] is not provided, you must supply [client] and optionally
/// [onAuthenticated] and [onError]. When [controller]
/// is provided, those parameters are handled by the controller itself.
///
/// Example with managed state:
/// ```
/// EmailOtpSignInWidget(
///   client: client,
///   onAuthenticated: () => Navigator.push(...),
///   onError: (error) => showSnackBar(...),
/// )
/// ```
///
/// Example with external controller:
/// ```
/// final controller = EmailOtpAuthController(
///   client: client,
///   onAuthenticated: ...,
/// );
///
/// EmailOtpSignInWidget(
///   controller: controller,
/// )
/// ```
class EmailOtpSignInWidget extends StatefulWidget {
  /// Controls the authentication state and behavior.
  ///
  /// If null, the widget creates and manages its own [EmailOtpAuthController].
  /// In this case, [client] must be provided.
  ///
  /// If provided, the widget uses this controller instead of creating one,
  /// and [client], [onAuthenticated], [onError], [allowPasswordSignIn],
  /// [emailValidation], and
  /// [passwordRequirements] are ignored.
  final EmailOtpAuthController? controller;

  /// The Serverpod client instance.
  ///
  /// Required when [controller] is null, ignored otherwise.
  final ServerpodClientShared? client;

  /// Callback when authentication is successful.
  ///
  /// Ignored when [controller] is provided.
  final VoidCallback? onAuthenticated;

  /// Callback when an error occurs during authentication.
  ///
  /// Ignored when [controller] is provided.
  final Function(Object error)? onError;

  /// Whether users can choose to sign in with their password on the start
  /// screen, see [EmailOtpAuthController.allowPasswordSignIn].
  ///
  /// Defaults to `false`. Ignored when [controller] is provided.
  final bool allowPasswordSignIn;

  /// Configuration for the one-time password input.
  ///
  /// Defaults to 6 digits. Make sure to match the configuration of the code
  /// generated by the server.
  final VerificationCodeConfig otpVerificationCodeConfig;

  /// Configuration for the password reset verification code input.
  ///
  /// Make sure to match the configuration of the code generated by the server.
  final VerificationCodeConfig verificationCodeConfig;

  /// The validation function to use for email validation.
  ///
  /// This function should throw an [InvalidEmailException] if the email is
  /// invalid. If null, the default validation accepts email aliases, e.g.
  /// email+alias@example.com. Ignored when [controller] is provided.
  final void Function(String email)? emailValidation;

  /// Optional list of password requirements to display to the user when
  /// setting a password.
  ///
  /// If null, will use a recommended safe default defined at
  /// [PasswordRequirement.defaultRequirements]. Ignored when [controller] is
  /// provided.
  final List<PasswordRequirement>? passwordRequirements;

  /// Optional callback to call when the terms and conditions button is pressed.
  ///
  /// If neither this nor [onPrivacyPolicyPressed] is provided, users are not
  /// asked to accept the terms when creating an account.
  final VoidCallback? onTermsAndConditionsPressed;

  /// Optional callback to call when the privacy policy button is pressed.
  ///
  /// If neither this nor [onTermsAndConditionsPressed] is provided, users are
  /// not asked to accept the terms when creating an account.
  final VoidCallback? onPrivacyPolicyPressed;

  /// Creates a passwordless email sign-in widget.
  const EmailOtpSignInWidget({
    this.controller,
    this.client,
    this.onAuthenticated,
    this.onError,
    this.allowPasswordSignIn = false,
    this.otpVerificationCodeConfig =
        EmailOtpFlowView.defaultOtpVerificationCodeConfig,
    this.verificationCodeConfig = const VerificationCodeConfig(),
    this.emailValidation,
    this.passwordRequirements,
    this.onTermsAndConditionsPressed,
    this.onPrivacyPolicyPressed,
    super.key,
  }) : assert(
         (controller == null) != (client == null),
         'Either controller or client must be provided, but not both. When '
         'passing a controller, client, onAuthenticated, and onError '
         'parameters are ignored.',
       ),
       assert(
         (onAuthenticated == null && onError == null) || controller == null,
         'Do not provide onAuthenticated or onError when using a controller '
         'as they will be handled by the controller and will be ignored.',
       );

  @override
  State<EmailOtpSignInWidget> createState() => _EmailOtpSignInWidgetState();
}

class _EmailOtpSignInWidgetState extends State<EmailOtpSignInWidget> {
  late final EmailOtpAuthController _controller;

  @override
  void initState() {
    super.initState();
    _controller =
        widget.controller ??
        EmailOtpAuthController(
          client: widget.client!,
          onAuthenticated: widget.onAuthenticated,
          onError: widget.onError,
          allowPasswordSignIn: widget.allowPasswordSignIn,
          emailValidation: widget.emailValidation,
          passwordRequirements: widget.passwordRequirements,
        );
  }

  @override
  void dispose() {
    if (widget.controller == null) {
      _controller.dispose();
    }
    super.dispose();
  }

  @override
  Widget build(BuildContext context) {
    return EmailOtpFlowView(
      controller: _controller,
      verificationCodeConfig: widget.verificationCodeConfig,
      otpVerificationCodeConfig: widget.otpVerificationCodeConfig,
      onTermsAndConditionsPressed: widget.onTermsAndConditionsPressed,
      onPrivacyPolicyPressed: widget.onPrivacyPolicyPressed,
    );
  }
}
