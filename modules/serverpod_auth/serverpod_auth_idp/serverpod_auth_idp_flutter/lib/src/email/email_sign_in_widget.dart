/// The methods offered by the [EmailSignInWidget] for users to sign in.
enum EmailLoginMethods {
  /// Sign in with email and password. Users can register and reset their
  /// password.
  password,

  /// Sign in with a verification code sent by email, without a password. An
  /// account is created when the code for a new email address is verified,
  /// unless sign-up is disabled on the server.
  passwordless,

  /// Sign in with either a password or a code sent by email. The login screen
  /// links to the passwordless login, and the passwordless login screen links
  /// back to the login with password.
  both,
}

/// A widget that provides email-based authentication functionality.
///
/// The widget can manage its own authentication state, or you can provide an
/// external [controller] for advanced use cases like sharing state across
/// multiple widgets or integrating with state management solutions.
///
/// When [controller] is not provided, you must supply [client] and optionally
/// [startScreen], [onAuthenticated], and [onError] callbacks. When [controller]
/// is provided, those parameters are handled by the controller itself.
///
/// Use [loginMethods] to choose whether users sign in with a password, with a
/// verification code sent by email (passwordless), or with either of them. The
/// passwordless login must be enabled on the server.
///
/// Example with managed state:
/// ```
/// EmailSignInWidget(
///   client: client,
///   onAuthenticated: () => Navigator.push(...),
///   onError: (error) => showSnackBar(...),
/// )
/// ```
///
/// Example with external controller:
/// ```
/// final controller = EmailAuthController(
///   client: client,
///   onAuthenticated: ...,
/// );
///
/// EmailSignInWidget(
///   controller: controller,
/// )
/// ```
class EmailSignInWidget extends StatefulWidget {
  /// Controls the authentication state and behavior.
  ///
  /// If null, the widget creates and manages its own [EmailAuthController].
  /// In this case, [client] must be provided.
  ///
  /// If provided, the widget uses this controller instead of creating one,
  /// and [client], [startScreen], [onAuthenticated], and [onError] are ignored.
  final EmailAuthController? controller;

  /// The Serverpod client instance.
  ///
  /// Required when [controller] is null, ignored otherwise.
  final ServerpodClientShared? client;

  /// The initial screen to display.
  ///
  /// Ignored when [controller] is provided, and when [loginMethods] is
  /// [EmailLoginMethods.passwordless], which always starts on the
  /// [EmailFlowScreen.passwordlessStart] screen.
  final EmailFlowScreen startScreen;

  /// The methods offered for users to sign in.
  ///
  /// Defaults to [EmailLoginMethods.password].
  final EmailLoginMethods loginMethods;

  /// Callback when authentication is successful.
  ///
  /// Ignored when [controller] is provided.
  final VoidCallback? onAuthenticated;

  /// Callback when an error occurs during authentication.
  ///
  /// Ignored when [controller] is provided.
  final Function(Object error)? onError;

  /// Configuration for the verification code input of the registration and
  /// password reset flows.
  ///
  /// Make sure to match the configuration of the code generated by the server.
  final VerificationCodeConfig verificationCodeConfig;

  /// Configuration for the verification code input of the passwordless login.
  ///
  /// Defaults to the 6 digit codes (`0`-`9`) generated by the server by
  /// default. Make sure to match the configuration of the code generated by the
  /// server, and to set a [VerificationCodeConfig.resendCountdownDuration] at
  /// least as long as the resend cooldown of the server.
  ///
  /// If the config has no [VerificationCodeConfig.allowedCharactersPattern],
  /// digits `0`-`9` are allowed. Unlike the codes of the registration and
  /// password reset flows, the default passwordless codes contain zeros, so a
  /// pattern that does not match `0` makes codes with a zero impossible to
  /// enter. A debug message is printed if the pattern does not match `0`,
  /// which is only right for a code generator that never produces it.
  final VerificationCodeConfig? passwordlessVerificationCodeConfig;

  /// The validation function to use for email validation.
  ///
  /// This function should throw a [FormatException] if the email is invalid.
  final void Function(String email)? emailValidation;

  /// Optional list of password requirements to display to the user.
  ///
  /// If provided, these requirements will be shown in password forms to guide
  /// users on password creation. If null, will use a recommended safe default
  /// defined at [PasswordRequirement.defaultRequirements].
  final List<PasswordRequirement>? passwordRequirements;

  /// Optional callback to call when the terms and conditions button is pressed.
  ///
  /// If not provided, defaults to null.
  final VoidCallback? onTermsAndConditionsPressed;

  /// Optional callback to call when the privacy policy button is pressed.
  ///
  /// If not provided, defaults to null.
  final VoidCallback? onPrivacyPolicyPressed;

  /// A widget shown below the email field on the passwordless login screen to
  /// inform the user about terms and conditions, a privacy policy, or any
  /// other consent that applies to creating an account.
  ///
  /// As sign-up happens implicitly when the code for an unknown email address
  /// is verified, this is the place to show the consent notice, for example a
  /// short `Text.rich` with links. The area above the button of the screen
  /// scrolls when the notice does not fit, so it can be as long as needed, but
  /// short notices make for a better experience.
  ///
  /// This is a notice and does not block the continue button. To require an
  /// explicit acceptance on the passwordless login screen, use
  /// [onTermsAndConditionsPressed] and [onPrivacyPolicyPressed] instead. If
  /// both are given, [consentNotice] is shown there.
  final Widget? consentNotice;

  /// Creates an email sign-in widget.
  const EmailSignInWidget({
    this.controller,
    this.client,
    this.startScreen = EmailFlowScreen.startRegistration,
    this.loginMethods = EmailLoginMethods.password,
    this.verificationCodeConfig = const VerificationCodeConfig(),
    this.passwordlessVerificationCodeConfig,
    this.emailValidation,
    this.passwordRequirements,
    this.onAuthenticated,
    this.onError,
    this.onTermsAndConditionsPressed,
    this.onPrivacyPolicyPressed,
    this.consentNotice,
    super.key,
  }) : assert(
         (controller == null) != (client == null),
         'Either controller or client must be provided, but not both. When '
         'passing a controller, client, startScreen, onAuthenticated, and '
         'onError parameters are ignored.',
       ),
       assert(
         (onAuthenticated == null && onError == null) || controller == null,
         'Do not provide onAuthenticated or onError when using a controller '
         'as they will be handled by the controller and will be ignored.',
       );

  @override
  State<EmailSignInWidget> createState() => _EmailSignInWidgetState();
}

class _EmailSignInWidgetState extends State<EmailSignInWidget> {
  late final EmailAuthController _controller;

  @override
  void initState() {
    super.initState();
    _controller =
        widget.controller ??
        EmailAuthController(
          client: widget.client!,
          startScreen: widget.loginMethods == EmailLoginMethods.passwordless
              ? EmailFlowScreen.passwordlessStart
              : widget.startScreen,
          onAuthenticated: widget.onAuthenticated,
          onError: widget.onError,
          emailValidation: widget.emailValidation,
          passwordRequirements: widget.passwordRequirements,
        );
    _controller.addListener(_onControllerStateChanged);
    _warnIfZeroIsNotAllowed(widget.passwordlessVerificationCodeConfig);
  }

  @override
  void didUpdateWidget(EmailSignInWidget oldWidget) {
    super.didUpdateWidget(oldWidget);
    if (oldWidget.passwordlessVerificationCodeConfig !=
        widget.passwordlessVerificationCodeConfig) {
      _warnIfZeroIsNotAllowed(widget.passwordlessVerificationCodeConfig);
    }
  }

  void _warnIfZeroIsNotAllowed(VerificationCodeConfig? config) {
    assert(() {
      final pattern = config?.allowedCharactersPattern;
      if (pattern != null && pattern.allMatches('0').isEmpty) {
        debugPrint(
          '[EmailSignInWidget] The allowedCharactersPattern of the '
          'passwordlessVerificationCodeConfig does not allow "0". The default '
          'codes of the passwordless login contain zeros, so users could not '
          'enter them. Use VerificationCodeConfig.numbersOnly or a pattern with '
          '0-9, unless the code generator of the server never produces a zero.',
        );
      }
      return true;
    }());
  }

  /// The passwordless codes have zeros, which the default pattern of the
  /// verification form (`[1-9]`, as used by the registration and password
  /// reset flows) would filter out.
  static VerificationCodeConfig _withDefaultPattern(
    VerificationCodeConfig config,
  ) {
    if (config.allowedCharactersPattern != null) return config;

    return VerificationCodeConfig(
      length: config.length,
      keyboardType: config.keyboardType,
      allowedLetterCase: config.allowedLetterCase,
      resendCountdownDuration: config.resendCountdownDuration,
      allowedCharactersPattern: RegExp(r'[0-9]'),
    );
  }

  @override
  void dispose() {
    _controller.removeListener(_onControllerStateChanged);
    if (widget.controller == null) {
      _controller.dispose();
    }
    super.dispose();
  }

  /// Rebuild when controller state changes
  void _onControllerStateChanged() {
    if (mounted) setState(() {});
  }

  @override
  Widget build(BuildContext context) {
    final texts = context.emailSignInTexts;

    return PageTransitionSwitcher(
      duration: const Duration(milliseconds: 600),
      reverse: _controller.currentScreen != _controller.startScreen,
      transitionBuilder: (child, primaryAnimation, secondaryAnimation) {
        return SharedAxisTransition(
          animation: primaryAnimation,
          secondaryAnimation: secondaryAnimation,
          transitionType: SharedAxisTransitionType.horizontal,
          fillColor: Colors.transparent,
          child: child,
        );
      },
      child: _buildScreen(texts),
    );
  }

  Widget _buildScreen(EmailSignInTexts texts) {
    return switch (_controller.currentScreen) {
      EmailFlowScreen.login => LoginForm(
        controller: _controller,
        showSignInWithCodeLink: widget.loginMethods == EmailLoginMethods.both,
      ),
      EmailFlowScreen.startRegistration => StartRegistrationForm(
        controller: _controller,
        onTermsAndConditionsPressed: widget.onTermsAndConditionsPressed,
        onPrivacyPolicyPressed: widget.onPrivacyPolicyPressed,
      ),
      EmailFlowScreen.verifyRegistration => VerificationForm(
        title: texts.verifyAccountTitle,
        messageText: texts.verificationMessage,
        controller: _controller,
        onCompleted: _controller.verifyRegistrationCode,
        verifyButtonLabel: texts.verify,
        verificationCodeConfig: widget.verificationCodeConfig,
      ),
      EmailFlowScreen.completeRegistration => CompleteRegistrationForm(
        controller: _controller,
      ),
      EmailFlowScreen.requestPasswordReset => RequestPasswordResetForm(
        controller: _controller,
      ),
      EmailFlowScreen.verifyPasswordReset => VerificationForm(
        title: texts.verifyResetCodeTitle,
        messageText: texts.verificationMessage,
        controller: _controller,
        onCompleted: _controller.verifyPasswordResetCode,
        verifyButtonLabel: texts.verify,
        verificationCodeConfig: widget.verificationCodeConfig,
      ),
      EmailFlowScreen.completePasswordReset => CompletePasswordResetForm(
        controller: _controller,
      ),
      EmailFlowScreen.passwordlessStart => PasswordlessLoginStartForm(
        controller: _controller,
        consentNotice: widget.consentNotice,
        onTermsAndConditionsPressed: widget.onTermsAndConditionsPressed,
        onPrivacyPolicyPressed: widget.onPrivacyPolicyPressed,
        showUsePasswordLink: widget.loginMethods == EmailLoginMethods.both,
      ),
      EmailFlowScreen.passwordlessVerify => VerificationForm(
        title: texts.passwordlessVerifyTitle,
        messageText: _controller.resendCooldownActive
            ? texts.passwordlessResendCooldownMessage
            : texts.passwordlessVerificationMessage,
        controller: _controller,
        onCompleted: () => unawaited(_controller.finishPasswordlessLogin()),
        verifyButtonLabel: texts.verify,
        verificationCodeConfig: _withDefaultPattern(
          widget.passwordlessVerificationCodeConfig ??
              VerificationCodeConfig.numbersOnly(length: 6),
        ),
        bottomText: Center(
          child: HyperlinkTextButton(
            onPressed: () =>
                _controller.navigateTo(EmailFlowScreen.passwordlessStart),
            padding: const EdgeInsets.symmetric(horizontal: 8),
            label: texts.passwordlessUseDifferentEmail,
          ),
        ),
      ),
    };
  }
}
