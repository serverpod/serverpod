import 'package:serverpod/serverpod.dart';
import 'package:serverpod_auth_idp_server/serverpod_auth_idp_server.dart'
    as auth_idp;
import 'package:serverpod_auth_test_server/src/generated/endpoints.dart';
import 'package:serverpod_auth_test_server/src/generated/protocol.dart';
import 'package:test/test.dart';

void main() {
  late Serverpod pod;

  setUpAll(() {
    pod = Serverpod(
      [],
      Protocol(),
      Endpoints(),
      config: ServerpodConfig(
        apiServer: ServerConfig(
          port: 0,
          publicScheme: 'http',
          publicHost: 'localhost',
          publicPort: 0,
        ),
      ),
    );
  });

  tearDownAll(() async {
    await pod.shutdown(exitProcess: false);
  });

  test(
    'Given the auth idp endpoints, which depend on the auth core module, '
    'when initializing them as projects generated by earlier versions do, '
    'then they hook up their auth core module.',
    () {
      final endpoints = auth_idp.Endpoints();

      endpoints.initializeEndpoints(pod.server);

      expect(endpoints.modules.keys, ['serverpod_auth_core']);
    },
  );

  test(
    'Given the auth idp endpoints, which depend on the auth core module, '
    'when initializing their own endpoints, '
    'then they hook up no modules.',
    () {
      final endpoints = auth_idp.Endpoints();

      endpoints.initializeOwnEndpoints(pod.server);

      expect(endpoints.modules, isEmpty);
    },
  );

  test(
    'Given the auth idp protocol, which depends on the auth core module, '
    'when getting its target table definitions as projects generated by earlier versions do, '
    'then they include the auth core tables.',
    () {
      final tables = auth_idp.Protocol().getTargetTableDefinitions();

      expect(
        tables.map((table) => table.module),
        contains('serverpod_auth_core'),
      );
    },
  );

  test(
    'Given the auth idp protocol, which depends on the auth core module, '
    'when getting its own table definitions, '
    'then only the auth idp tables are returned.',
    () {
      final tables = auth_idp.Protocol().getOwnTableDefinitions();

      expect(tables.map((table) => table.module).toSet(), {
        'serverpod_auth_idp',
      });
    },
  );
}
